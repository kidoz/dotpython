namespace DotPython.Language.Ast;

// Explicit child edges keep traversal independent of reflection and runtime metadata.
/// <summary>Enumerates immediate AST children without applying scope or source-offset semantics.</summary>
public static class PythonAstTraversal
{
    public static IEnumerable<PythonNode?> GetChildren(PythonNode node) =>
        node switch
        {
            null => throw new ArgumentNullException(nameof(node)),
            PythonModule n => [.. n.Statements],
            PythonAssignmentStatement n => [n.Target, n.Value, .. (n.ChainedTargets ?? [])],
            PythonAugmentedAssignmentStatement n => [n.Target, n.Value],
            PythonExpressionStatement n => [n.Expression],
            PythonAnnotatedAssignmentStatement n => [n.Target, n.Annotation, n.Value],
            PythonFunctionDefinitionStatement n =>
            [
                .. n.Decorators,
                n.Name,
                .. n.Parameters,
                .. n.Body,
                n.ReturnAnnotation,
            ],
            PythonClassDefinitionStatement n =>
            [
                .. n.Decorators,
                n.Name,
                .. n.Bases,
                .. n.Body,
                .. (n.KeywordArguments ?? []),
            ],
            PythonParameter n => [n.Default, n.Annotation],
            PythonReturnStatement n => [n.Value],
            PythonBreakStatement => [],
            PythonContinueStatement => [],
            PythonPassStatement => [],
            PythonAssertStatement n => [n.Condition, n.Message],
            PythonDeleteStatement n => [.. n.Targets],
            PythonGlobalStatement n => [.. n.Names],
            PythonNonlocalStatement n => [.. n.Names],
            PythonRaiseStatement n => [n.Exception, n.Cause],
            PythonImportStatement n => [.. n.Imports],
            PythonFromImportStatement n => [.. n.Imports],
            PythonImportAlias => [],
            PythonIfStatement n => [.. n.Clauses, .. n.ElseBody],
            PythonConditionalClause n => [n.Condition, .. n.Body],
            PythonWhileStatement n => [n.Condition, .. n.Body, .. n.ElseBody],
            PythonForStatement n => [n.Target, n.Iterable, .. n.Body, .. n.ElseBody],
            PythonWithStatement n => [.. n.Items, .. n.Body],
            PythonWithItem n => [n.Context, n.Target],
            PythonTryStatement n => [.. n.Body, .. n.Handlers, .. n.ElseBody, .. n.FinallyBody],
            PythonExceptHandler n => [n.Type, n.Target, .. n.Body],
            PythonMatchStatement n => [n.Subject, .. n.Cases],
            PythonMatchCase n => [n.Pattern, n.Guard, .. n.Body],
            PythonLiteralPattern n => [n.Literal],
            PythonCapturePattern => [],
            PythonValuePattern n => [n.DottedName],
            PythonSequencePattern n => [.. n.Patterns],
            PythonMappingPattern n => [.. n.Items],
            PythonMappingPatternItem n => [n.Key, n.Pattern],
            PythonClassPattern n => [n.Cls, .. n.Positional, .. n.Keyword],
            PythonClassPatternKeyword n => [n.Pattern],
            PythonOrPattern n => [.. n.Alternatives],
            PythonAsPattern n => [n.Inner],
            PythonNameExpression => [],
            PythonConstantExpression => [],
            PythonUnaryExpression n => [n.Operand],
            PythonBinaryExpression n => [n.Left, n.Right],
            PythonComparisonExpression n => [n.Left, .. n.Comparisons],
            PythonComparisonPart n => [n.Right],
            PythonCallExpression n => [n.Target, .. n.Arguments, .. n.KeywordArguments],
            PythonKeywordArgument n => [n.Value],
            PythonStarredExpression n => [n.Operand],
            PythonListExpression n => [.. n.Elements],
            PythonSetExpression n => [.. n.Elements],
            PythonLambdaExpression n => [.. n.Parameters, n.Body],
            PythonGeneratorExpression n => [n.Element, .. n.Clauses],
            PythonSetComprehensionExpression n => [n.Element, .. n.Clauses],
            PythonYieldExpression n => [n.Value],
            PythonYieldFromExpression n => [n.Source],
            PythonAwaitExpression n => [n.Operand],
            PythonAssignmentExpression n => [n.Target, n.Value],
            PythonConditionalExpression n => [n.Condition, n.TrueResult, n.FalseResult],
            PythonTemplateStringExpression n => [.. n.Parts],
            PythonFormattedStringExpression n => [.. n.Parts],
            PythonFormattedStringLiteralPart => [],
            PythonFormattedStringInterpolationPart n => [n.Expression],
            PythonComprehensionForClause n => [n.Target, n.Iterable],
            PythonComprehensionIfClause n => [n.Condition],
            PythonListComprehensionExpression n => [n.Element, .. n.Clauses],
            PythonDictionaryComprehensionExpression n => [n.Key, n.Value, .. n.Clauses],
            PythonTupleExpression n => [.. n.Elements],
            PythonDictionaryExpression n => [.. n.Items],
            PythonDictionaryItem n => [n.Key, n.Value],
            PythonSubscriptionExpression n => [n.Target, n.Index],
            PythonSliceExpression n => [n.Start, n.Stop, n.Step],
            PythonAttributeExpression n => [n.Target],
            PythonParenthesizedExpression n => [n.Expression],
            _ => throw new NotSupportedException(
                $"Unknown Python AST node: {node.GetType().Name}."
            ),
        };
}
